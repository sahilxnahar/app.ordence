export type RecordOperation = "read" | "create" | "update" | "delete";

/**
 * The permission a step needs, or null when the operation is not offered
 * on that record type at all.
 *
 * ⚠️ RETURNS null FOR BOTH "unknown record type" AND "operation not
 * supported", and the caller must treat both as a refusal. An engine that
 * distinguished them by running the step would be deciding policy from
 * the shape of an error.
 */
export function permissionForRecordAction(
  recordType: unknown,
  operation: RecordOperation,
): string | null {
  const definition = recordTypeFor(recordType);
  if (!definition) return null;
  return definition.permissions[operation];
}

/**
 * Split a set of proposed column writes into the ones that are allowed
 * and the ones that are not.
 *
 * Returns both halves rather than throwing, because the run history needs
 * to say WHICH column was refused. "That workflow does not work" is the
 * support ticket; "step 3 tried to write `tenant_id` on a lead" is the
 * answer.
 */
export function partitionWritableColumns(
  recordType: unknown,
  columns: readonly string[],
): { allowed: string[]; refused: string[] } {
  const definition = recordTypeFor(recordType);
  if (!definition) return { allowed: [], refused: [...columns] };

  const allowed: string[] = [];
  const refused: string[] = [];
  for (const column of columns) {
    if (definition.writableColumns.includes(column)) allowed.push(column);
    else refused.push(column);
  }
  return { allowed, refused };
}

export function isReadableColumn(recordType: unknown, column: string): boolean {
  const definition = recordTypeFor(recordType);
  return definition ? definition.readableColumns.includes(column) : false;
}
