-- Check 5 — ⭐⭐ THE RAW STATEMENT CANNOT BE DESTROYED, AND A FAILED PARSE
-- STILL LEAVES IT INTACT.
--
-- Proved rather than inspected: a trigger whose condition is subtly inverted
-- passes every "does it exist" check. This stores a document, marks the parse
-- FAILED (which is the ordinary path when a file will not parse), reads the raw
-- back, and then tries to blank it.
DO $$
DECLARE
  v_tenant   uuid := gen_random_uuid();
  v_doc      uuid := gen_random_uuid();
  v_raw      jsonb;
  v_marked   boolean := false;
  v_intact   boolean := false;
  v_refused  boolean := false;
BEGIN
  INSERT INTO tenants (id, clerk_org_id, slug, name, status)
    VALUES (v_tenant, 'org_2braw_' || v_tenant, 'raw-' || left(v_tenant::text, 8),
            'GSTR-2B raw verification', 'active');

  INSERT INTO gstr2b_documents
    (id, tenant_id, gstin, return_period, source_format, file_hash, raw_document)
    VALUES (v_doc, v_tenant, '27AAACR5055K1ZQ', '2024-07', 'portal_json',
            repeat('a', 64),
            '{"data":{"gstin":"27AAACR5055K1ZQ","rtnprd":"072024","docdata":{"b2b":[]}}}'::jsonb);

  -- The ordinary failed-parse path. MUST be accepted: refusing it is how the
  -- raw file gets thrown away, because the caller then rolls the whole
  -- transaction back.
  BEGIN
    UPDATE gstr2b_documents
       SET parse_status = 'failed',
           parse_error  = 'Unexpected token at data.docdata.b2b[0]',
           row_count    = 0
     WHERE id = v_doc;
    v_marked := true;
  EXCEPTION WHEN OTHERS THEN
    v_marked := false;
    RAISE NOTICE 'marking a parse failed was refused: %', SQLERRM;
  END;

  SELECT raw_document INTO v_raw FROM gstr2b_documents WHERE id = v_doc;
  v_intact := v_raw IS NOT NULL AND v_raw <> 'null'::jsonb
              AND v_raw #>> '{data,gstin}' = '27AAACR5055K1ZQ';

  -- ⭐ And the raw itself. MUST be refused.
  BEGIN
    UPDATE gstr2b_documents SET raw_document = '{}'::jsonb WHERE id = v_doc;
  EXCEPTION WHEN OTHERS THEN
    v_refused := true;
  END;

  IF v_marked AND v_intact AND v_refused THEN
    RAISE NOTICE 'PASS: ⭐ a malformed statement is recorded as failed WITHOUT '
                 'destroying the raw document, and the raw document cannot be '
                 'overwritten.';
  ELSIF NOT v_marked THEN
    RAISE WARNING '*** FAIL — marking a parse as failed was refused, so the only '
                  'way to record a bad file is to roll back the transaction that '
                  'stored it. The raw file is then lost, and a parse bug found a '
                  'year later has nothing to re-read. ***';
  ELSIF NOT v_intact THEN
    RAISE WARNING '*** FAIL — ⭐⭐ THE RAW DOCUMENT DID NOT SURVIVE A FAILED '
                  'PARSE. It is the only artefact the customer cannot reconstruct '
                  'from their own paper. ***';
  ELSE
    RAISE WARNING '*** FAIL — the raw GSTR-2B was OVERWRITTEN. Every parsed row is '
                  'an interpretation of it; without it, the only remaining copy of '
                  'what the Government said about us is our opinion of what the '
                  'Government said about us. ***';
  END IF;

  RAISE EXCEPTION 'verification rollback';
EXCEPTION WHEN OTHERS THEN
  IF SQLERRM <> 'verification rollback' THEN
    RAISE WARNING '*** FAIL — verification could not run: % ***', SQLERRM;
  END IF;
END
$$;


