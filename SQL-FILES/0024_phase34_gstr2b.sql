-- ⭐ The same bytes imported twice are ONE document, not two. The file hash is
-- part of the key because 2B for a period is REGENERATED when a supplier files
-- late: July downloaded in August and July downloaded in November are
-- different documents describing the same month, and both are evidence.
CREATE UNIQUE INDEX IF NOT EXISTS gstr2b_documents_identity_unique
  ON gstr2b_documents (tenant_id, gstin, return_period, file_hash);
CREATE INDEX IF NOT EXISTS gstr2b_documents_period_idx
  ON gstr2b_documents (tenant_id, gstin, return_period);
CREATE INDEX IF NOT EXISTS gstr2b_documents_status_idx
  ON gstr2b_documents (tenant_id, parse_status);

CREATE INDEX IF NOT EXISTS gstr2b_rows_document_idx
  ON gstr2b_rows (tenant_id, document_id);
CREATE INDEX IF NOT EXISTS gstr2b_rows_section_idx
  ON gstr2b_rows (tenant_id, document_id, section);
-- ⭐ The candidate lookup the workbench searches on.
CREATE INDEX IF NOT EXISTS gstr2b_rows_match_idx
  ON gstr2b_rows (tenant_id, supplier_gstin, normalised_number);
CREATE INDEX IF NOT EXISTS gstr2b_rows_supplier_idx
  ON gstr2b_rows (tenant_id, supplier_gstin, invoice_date);

-- ⭐ ONE RECONCILIATION PER GSTIN PER PERIOD. This is the freeze key: the
-- trigger in Section 6 looks a period up by exactly these three columns.
CREATE UNIQUE INDEX IF NOT EXISTS gstr2b_reconciliations_period_unique
  ON gstr2b_reconciliations (tenant_id, gstin, tax_period);
CREATE INDEX IF NOT EXISTS gstr2b_reconciliations_status_idx
  ON gstr2b_reconciliations (tenant_id, status);
CREATE INDEX IF NOT EXISTS gstr2b_reconciliations_registration_idx
  ON gstr2b_reconciliations (tenant_id, registration_id, tax_period);

CREATE INDEX IF NOT EXISTS gstr2b_matches_worklist_idx
  ON gstr2b_matches (tenant_id, reconciliation_id, match_category, action);
CREATE INDEX IF NOT EXISTS gstr2b_matches_supplier_idx
  ON gstr2b_matches (tenant_id, supplier_gstin, match_category);
CREATE INDEX IF NOT EXISTS gstr2b_matches_vendor_idx
  ON gstr2b_matches (tenant_id, vendor_id);
CREATE INDEX IF NOT EXISTS gstr2b_matches_invoice_idx
  ON gstr2b_matches (tenant_id, purchase_invoice_id);


-- ############################################################################
-- SECTION 2 — ⭐ ONE MATCH PER DOCUMENT
-- ############################################################################
--
-- THE TWO INDEXES THAT MAKE THE SUMMARY ADD UP.
--
--     A re-run of the engine appends instead of replacing. One 2B row is now
--     matched to two purchase invoices. Both match rows look perfectly
--     ordinary — same supplier, same number, sensible confidence. The
--     "matched" total exceeds the books total by one invoice, "in books, not
--     in 2B" shrinks by one, and the reconciliation reports one fewer supplier
--     to chase.
--
-- Nothing on any screen looks wrong. The identity CHECKs on
-- `gstr2b_reconciliations` would catch the totals at COMMIT — which is the
-- right failure — but these catch it at the row that caused it, which is the
-- one a person can act on.
--
-- ⚠️ PARTIAL, ON `IS NOT NULL`. A one-sided exception has a NULL on the other
-- side, and PostgreSQL treats NULLs as distinct in a unique index — so without
-- the WHERE clause the index would be built over rows it cannot constrain and
-- would say nothing about the ones it can.

CREATE UNIQUE INDEX IF NOT EXISTS gstr2b_matches_one_per_2b_row
  ON gstr2b_matches (tenant_id, reconciliation_id, gstr2b_row_id)
  WHERE gstr2b_row_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS gstr2b_matches_one_per_invoice
  ON gstr2b_matches (tenant_id, reconciliation_id, purchase_invoice_id)
  WHERE purchase_invoice_id IS NOT NULL;


-- ############################################################################
-- SECTION 3 — ROW-LEVEL SECURITY
-- ############################################################################
--
-- ENABLE turns policies on. FORCE applies them to the table OWNER too, which
-- is the half everybody forgets: without it the role that created the table
-- reads everything and the policies look like they are working.
--
-- ⚠️ NO `app_is_platform_scope()` ON ANY POLICY HERE, AND THE ARGUMENT IS
-- STRONGER THAN FOR PHASE 33. A tenant's GSTR-2B is a list, issued by the
-- Government, of every supplier who invoiced them in a month, with amounts. It
-- is a more complete and more reliable supplier list than their own purchase
-- ledger, because it was compiled by somebody with no incentive to leave
-- anything out. Platform staff have no business reading it.

ALTER TABLE gstr2b_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE gstr2b_documents FORCE  ROW LEVEL SECURITY;
DROP POLICY IF EXISTS gstr2b_documents_tenant_isolation ON gstr2b_documents;
CREATE POLICY gstr2b_documents_tenant_isolation ON gstr2b_documents
  USING (tenant_id = app_current_tenant_id())
  WITH CHECK (tenant_id = app_current_tenant_id());

ALTER TABLE gstr2b_rows ENABLE ROW LEVEL SECURITY;
ALTER TABLE gstr2b_rows FORCE  ROW LEVEL SECURITY;
DROP POLICY IF EXISTS gstr2b_rows_tenant_isolation ON gstr2b_rows;
CREATE POLICY gstr2b_rows_tenant_isolation ON gstr2b_rows
  USING (tenant_id = app_current_tenant_id())
  WITH CHECK (tenant_id = app_current_tenant_id());

ALTER TABLE gstr2b_reconciliations ENABLE ROW LEVEL SECURITY;
ALTER TABLE gstr2b_reconciliations FORCE  ROW LEVEL SECURITY;
DROP POLICY IF EXISTS gstr2b_reconciliations_tenant_isolation ON gstr2b_reconciliations;
CREATE POLICY gstr2b_reconciliations_tenant_isolation ON gstr2b_reconciliations
  USING (tenant_id = app_current_tenant_id())
  WITH CHECK (tenant_id = app_current_tenant_id());

ALTER TABLE gstr2b_matches ENABLE ROW LEVEL SECURITY;
ALTER TABLE gstr2b_matches FORCE  ROW LEVEL SECURITY;
DROP POLICY IF EXISTS gstr2b_matches_tenant_isolation ON gstr2b_matches;
CREATE POLICY gstr2b_matches_tenant_isolation ON gstr2b_matches
  USING (tenant_id = app_current_tenant_id())
  WITH CHECK (tenant_id = app_current_tenant_id());


-- ############################################################################
-- SECTION 4 — ⭐ COMPOSITE FOREIGN KEYS
-- ############################################################################
--
-- ⚠️ FOREIGN-KEY CHECKS RUN AS THE SYSTEM AND IGNORE ROW-LEVEL SECURITY. That
-- is documented PostgreSQL behaviour and it is why every pointer in this phase
-- is a COMPOSITE key on (col, tenant_id).
--
-- The shape of the hole, concretely for this phase:
--
--     Tenant A inserts a match with
--         tenant_id           = A                            ← passes WITH CHECK
--         purchase_invoice_id = <an invoice owned by B>       ← passes a single FK
--
--     A's reconciliation now claims that B's purchase invoice was matched to a
--     supplier declaration. Worse, it is an EXISTENCE ORACLE for the most
--     commercially sensitive identifier in the product: guessing invoice ids
--     until one is accepted enumerates another developer's purchase ledger,
--     and the "matched" flag confirms each hit.

CREATE UNIQUE INDEX IF NOT EXISTS gstr2b_documents_id_tenant_key
  ON gstr2b_documents (id, tenant_id);
CREATE UNIQUE INDEX IF NOT EXISTS gstr2b_rows_id_tenant_key
  ON gstr2b_rows (id, tenant_id);
CREATE UNIQUE INDEX IF NOT EXISTS gstr2b_reconciliations_id_tenant_key
  ON gstr2b_reconciliations (id, tenant_id);

-- Parents in earlier phases. Created idempotently so this file does not depend
-- on the order the SQL directory is applied in.
CREATE UNIQUE INDEX IF NOT EXISTS users_id_tenant_key
  ON users (id, tenant_id);
CREATE UNIQUE INDEX IF NOT EXISTS gst_registrations_id_tenant_key
  ON gst_registrations (id, tenant_id);
CREATE UNIQUE INDEX IF NOT EXISTS vendors_id_tenant_key
  ON vendors (id, tenant_id);
CREATE UNIQUE INDEX IF NOT EXISTS purchase_invoices_id_tenant_key
  ON purchase_invoices (id, tenant_id);

DO $$
BEGIN
  /* --- gstr2b_documents ------------------------------------------ */
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'gstr2b_documents_registration_same_tenant') THEN
    ALTER TABLE gstr2b_documents
      ADD CONSTRAINT gstr2b_documents_registration_same_tenant
      FOREIGN KEY (registration_id, tenant_id)
      REFERENCES gst_registrations (id, tenant_id)
      -- ⚠️ RESTRICT. The statement was generated for THAT GSTIN and the credit
      -- in it belongs to THAT electronic credit ledger. Losing the pointer
      -- loses which state the credit is in.
      ON DELETE RESTRICT;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'gstr2b_documents_imported_by_same_tenant') THEN
    ALTER TABLE gstr2b_documents
      ADD CONSTRAINT gstr2b_documents_imported_by_same_tenant
      FOREIGN KEY (imported_by, tenant_id) REFERENCES users (id, tenant_id)
      ON DELETE SET NULL (imported_by);
  END IF;

  /* --- gstr2b_rows ----------------------------------------------- */
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'gstr2b_rows_document_same_tenant') THEN
    ALTER TABLE gstr2b_rows ADD CONSTRAINT gstr2b_rows_document_same_tenant
      FOREIGN KEY (document_id, tenant_id)
      -- CASCADE: the rows are DERIVED. Dropping the statement drops its
      -- interpretation, which is correct — the raw document is the evidence
      -- and it cannot be dropped by the application at all (Section 10).
      REFERENCES gstr2b_documents (id, tenant_id) ON DELETE CASCADE;
  END IF;

  /* --- gstr2b_reconciliations ------------------------------------ */
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'gstr2b_reconciliations_registration_same_tenant') THEN
    ALTER TABLE gstr2b_reconciliations
      ADD CONSTRAINT gstr2b_reconciliations_registration_same_tenant
      FOREIGN KEY (registration_id, tenant_id)
      REFERENCES gst_registrations (id, tenant_id) ON DELETE RESTRICT;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'gstr2b_reconciliations_document_same_tenant') THEN
    ALTER TABLE gstr2b_reconciliations
      ADD CONSTRAINT gstr2b_reconciliations_document_same_tenant
      FOREIGN KEY (document_id, tenant_id)
      -- ⚠️ RESTRICT. A reconciliation names the statement it was built from,
      -- and a filed one is a working paper for a return the Government holds.
      REFERENCES gstr2b_documents (id, tenant_id) ON DELETE RESTRICT;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'gstr2b_reconciliations_filed_by_same_tenant') THEN
    ALTER TABLE gstr2b_reconciliations
      ADD CONSTRAINT gstr2b_reconciliations_filed_by_same_tenant
      FOREIGN KEY (filed_by, tenant_id) REFERENCES users (id, tenant_id)
      ON DELETE SET NULL (filed_by);
  END IF;

  /* --- gstr2b_matches -------------------------------------------- */
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'gstr2b_matches_reconciliation_same_tenant') THEN
    ALTER TABLE gstr2b_matches
      ADD CONSTRAINT gstr2b_matches_reconciliation_same_tenant
      FOREIGN KEY (reconciliation_id, tenant_id)
      REFERENCES gstr2b_reconciliations (id, tenant_id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'gstr2b_matches_row_same_tenant') THEN
    ALTER TABLE gstr2b_matches ADD CONSTRAINT gstr2b_matches_row_same_tenant
      FOREIGN KEY (gstr2b_row_id, tenant_id)
      REFERENCES gstr2b_rows (id, tenant_id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'gstr2b_matches_invoice_same_tenant') THEN
    ALTER TABLE gstr2b_matches ADD CONSTRAINT gstr2b_matches_invoice_same_tenant
      FOREIGN KEY (purchase_invoice_id, tenant_id)
      REFERENCES purchase_invoices (id, tenant_id)
      -- ⭐ RESTRICT. A purchase invoice that has been reconciled against a
      -- filed return cannot be deleted; the match is the evidence for the
      -- credit that was — or was not — claimed on it.
      ON DELETE RESTRICT;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'gstr2b_matches_vendor_same_tenant') THEN
    ALTER TABLE gstr2b_matches ADD CONSTRAINT gstr2b_matches_vendor_same_tenant
      FOREIGN KEY (vendor_id, tenant_id) REFERENCES vendors (id, tenant_id)
      ON DELETE SET NULL (vendor_id);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'gstr2b_matches_action_by_same_tenant') THEN
    ALTER TABLE gstr2b_matches ADD CONSTRAINT gstr2b_matches_action_by_same_tenant
      FOREIGN KEY (action_by, tenant_id) REFERENCES users (id, tenant_id)
      -- ⚠️ SET NULL, and it is the WRONG shape for evidence — but the
      -- alternative is worse. RESTRICT here would mean a person who accepted
      -- one match can never be removed from the workspace, and the answer to
      -- an offboarding request would be "no". The audit trail for WHO decided
      -- lives in `change_log` and `audit_logs`, which do not lose it.
      ON DELETE SET NULL (action_by);
  END IF;
END
$$;


-- ############################################################################
-- SECTION 5 — ⭐ THE RAW STATEMENT IS IMMUTABLE
-- ############################################################################
--
-- THE MOST IMPORTANT TRIGGER IN THE PHASE, AND THE ONE WITH THE LEAST
-- IMPRESSIVE MECHANISM.
--
--     `gstr2b_documents.raw_document` is the file the portal served. Every
--     parsed row is an INTERPRETATION of it. A parse bug is discovered, by
--     definition, after the parse — usually a year later, at a notice — and by
--     then the portal may no longer serve that month.
--
--     If a re-import, a "cleanup", or a well-meaning correction overwrote the
--     raw document with our own interpretation of it, there is nothing left to
--     re-read. The only remaining copy of what the Government said about us
--     would be our opinion of what the Government said about us.
--
-- So the file, its hash, its GSTIN and its period are frozen at insert.
-- `parse_status`, `parse_error`, `parse_issues`, `row_count` and `parsed_at`
-- stay editable, because re-parsing the SAME bytes with a FIXED parser is
-- exactly the operation this design exists to make possible.
--
-- ⚠️ A TRIGGER RATHER THAN A REVOKED UPDATE, because the row must remain
-- updatable for the parse columns. Column-level GRANTs could express it and
-- would be silent about WHY the update failed — and the "why" is the whole
-- content of this section.

CREATE OR REPLACE FUNCTION enforce_gstr2b_raw_immutable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.raw_document IS DISTINCT FROM OLD.raw_document THEN
    RAISE EXCEPTION
      'The raw GSTR-2B statement for % (%) cannot be changed. It is the file the '
      'portal served, and every parsed row is an interpretation of it. A parse '
      'bug is found after the parse — often a year later at a notice — and by '
      'then the portal may no longer serve that month. Re-parse the stored '
      'document instead: rebuild the rows and update parse_status.',
      OLD.gstin, OLD.return_period
      USING ERRCODE = '42501';
  END IF;

  IF NEW.file_hash IS DISTINCT FROM OLD.file_hash
     OR NEW.gstin IS DISTINCT FROM OLD.gstin
     OR NEW.return_period IS DISTINCT FROM OLD.return_period
     OR NEW.source_format IS DISTINCT FROM OLD.source_format THEN
    RAISE EXCEPTION
      'The identity of an imported GSTR-2B statement — its hash, its GSTIN, its '
      'period and its format — cannot be changed. Those four are what let a '
      'later reader say THIS is the file the portal gave us; a mutable identity '
      'says nothing at all. Import the other file as a new document.'
      USING ERRCODE = '42501';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS gstr2b_documents_raw_immutable ON gstr2b_documents;
CREATE TRIGGER gstr2b_documents_raw_immutable
  BEFORE UPDATE ON gstr2b_documents
  FOR EACH ROW EXECUTE FUNCTION enforce_gstr2b_raw_immutable();


-- ############################################################################
-- SECTION 6 — ⭐⭐ A FILED PERIOD FREEZES
-- ############################################################################
--
-- THE RULE:
--
--     Once a GSTR-3B has been filed for a period, the reconciliation that
--     supported it is a working paper for a document the Government holds a
--     copy of. Nothing about it may change — not the totals, not the matches,
--     and NOT BY RE-IMPORTING THE PERIOD.
--
-- ⚠️ THE RE-IMPORT IS THE CASE THAT MATTERS, AND IT IS ORDINARY WORK. The
-- portal REGENERATES GSTR-2B for a period whenever a supplier files their
-- GSTR-1 late. July's statement downloaded in August and July's statement
-- downloaded in November are different documents describing the same month.
-- Importing the November one is exactly the right thing to do — the late
-- filing means credit is now available — but the credit is available IN
-- NOVEMBER, in November's return, and July's filed figures must not move.
--
-- Without this trigger the second import would rewrite July: the totals would
-- change, the "in books, not in 2B" list would shrink, and the working paper
-- for a return already submitted would no longer describe what was submitted.
-- Nothing would error and nothing would say it had changed.
--
-- ⚠️ AND THE REFUSAL IS A SENTENCE THAT SAYS WHAT TO DO INSTEAD, because the
-- person hitting it is doing something reasonable and needs to be redirected
-- rather than blocked.

CREATE OR REPLACE FUNCTION enforce_gstr2b_period_not_filed()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_filed_at    timestamptz;
  v_reference   varchar(64);
BEGIN
  SELECT r.filed_at, r.filed_reference
    INTO v_filed_at, v_reference
    FROM gstr2b_reconciliations r
   WHERE r.tenant_id  = NEW.tenant_id
     AND r.gstin      = NEW.gstin
     AND r.tax_period = NEW.return_period
     AND r.status     = 'filed';

  IF FOUND AND v_filed_at IS NOT NULL THEN
    RAISE EXCEPTION
      'GSTR-2B for % % has already been reconciled and FILED (% , %). A filed '
      'period cannot be re-imported. The portal regenerates 2B whenever a '
      'supplier files late, so this file is almost certainly newer than the one '
      'the return was built from — and the credit it unlocks belongs to the '
      'CURRENT period''s return, not to a return already submitted. Import it '
      'against the period you are filing now.',
      NEW.gstin, NEW.return_period, COALESCE(v_reference, 'no ARN recorded'),
      to_char(v_filed_at, 'YYYY-MM-DD')
      USING ERRCODE = '42501';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS gstr2b_documents_period_not_filed ON gstr2b_documents;
CREATE TRIGGER gstr2b_documents_period_not_filed
  BEFORE INSERT ON gstr2b_documents
  FOR EACH ROW EXECUTE FUNCTION enforce_gstr2b_period_not_filed();


-- The reconciliation itself. ⚠️ `notes` STAYS EDITABLE, DELIBERATELY: a note
-- added after filing ("supplier confirmed they filed on 14 Dec, credit taken in
-- December") is a fact about the past, not a change to it, and forbidding it
-- would push the same sentence into a spreadsheet nobody else can see.
CREATE OR REPLACE FUNCTION enforce_gstr2b_reconciliation_frozen()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF OLD.status <> 'filed' THEN
    RETURN NEW;
  END IF;

  IF NEW.status              IS DISTINCT FROM OLD.status
     OR NEW.gstin            IS DISTINCT FROM OLD.gstin
     OR NEW.tax_period       IS DISTINCT FROM OLD.tax_period
     OR NEW.document_id      IS DISTINCT FROM OLD.document_id
     OR NEW.filed_at         IS DISTINCT FROM OLD.filed_at
     OR NEW.filed_by         IS DISTINCT FROM OLD.filed_by
     OR NEW.filed_reference  IS DISTINCT FROM OLD.filed_reference
     OR NEW.books_invoice_count          IS DISTINCT FROM OLD.books_invoice_count
     OR NEW.books_taxable_minor          IS DISTINCT FROM OLD.books_taxable_minor
     OR NEW.books_tax_minor              IS DISTINCT FROM OLD.books_tax_minor
     OR NEW.books_itc_eligible_minor     IS DISTINCT FROM OLD.books_itc_eligible_minor
     OR NEW.twob_row_count               IS DISTINCT FROM OLD.twob_row_count
     OR NEW.twob_taxable_minor           IS DISTINCT FROM OLD.twob_taxable_minor
     OR NEW.twob_tax_minor               IS DISTINCT FROM OLD.twob_tax_minor
     OR NEW.twob_itc_available_minor     IS DISTINCT FROM OLD.twob_itc_available_minor
     OR NEW.matched_count                IS DISTINCT FROM OLD.matched_count
     OR NEW.matched_books_tax_minor      IS DISTINCT FROM OLD.matched_books_tax_minor
     OR NEW.matched_twob_tax_minor       IS DISTINCT FROM OLD.matched_twob_tax_minor
     OR NEW.in_books_not_in_2b_count     IS DISTINCT FROM OLD.in_books_not_in_2b_count
     OR NEW.in_books_not_in_2b_tax_minor IS DISTINCT FROM OLD.in_books_not_in_2b_tax_minor
     OR NEW.in_2b_not_in_books_count     IS DISTINCT FROM OLD.in_2b_not_in_books_count
     OR NEW.in_2b_not_in_books_tax_minor IS DISTINCT FROM OLD.in_2b_not_in_books_tax_minor
     OR NEW.itc_at_risk_minor            IS DISTINCT FROM OLD.itc_at_risk_minor
     OR NEW.itc_claimed_minor            IS DISTINCT FROM OLD.itc_claimed_minor THEN
    RAISE EXCEPTION
      'The GSTR-2B reconciliation for % % was FILED on % and cannot be changed. '
      'It is the working paper for a GSTR-3B the Government holds a copy of. A '
      'return that has been filed cannot be unfiled — a period that turns out to '
      'be wrong is corrected in a LATER period, which is how the electronic '
      'credit ledger itself behaves and the only way the books can go on '
      'agreeing with the returns already submitted.',
      OLD.gstin, OLD.tax_period, to_char(OLD.filed_at, 'YYYY-MM-DD')
      USING ERRCODE = '42501';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS gstr2b_reconciliations_frozen ON gstr2b_reconciliations;
CREATE TRIGGER gstr2b_reconciliations_frozen
  BEFORE UPDATE ON gstr2b_reconciliations
  FOR EACH ROW EXECUTE FUNCTION enforce_gstr2b_reconciliation_frozen();


-- And the matches under a filed reconciliation. ⚠️ INSERT, UPDATE **AND**
-- DELETE: a re-run that deleted the old matches and wrote new ones would leave
-- the totals intact and every explanation replaced, which is the worst of both
-- — a filed working paper whose reasoning is no longer the reasoning that was
-- used.
CREATE OR REPLACE FUNCTION enforce_gstr2b_match_not_filed()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_row       gstr2b_matches%ROWTYPE;
  v_gstin     varchar(15);
  v_period    varchar(7);
  v_filed_at  timestamptz;
BEGIN
  v_row := COALESCE(NEW, OLD);

  SELECT r.gstin, r.tax_period, r.filed_at
    INTO v_gstin, v_period, v_filed_at
    FROM gstr2b_reconciliations r
   WHERE r.id = v_row.reconciliation_id
     AND r.status = 'filed';

  IF FOUND AND v_filed_at IS NOT NULL THEN
    RAISE EXCEPTION
      'The GSTR-2B reconciliation for % % was FILED on %. Its matches are the '
      'evidence for every credit taken and every credit withheld in that return, '
      'and they cannot be added to, changed or removed. Reconcile the current '
      'period instead.',
      v_gstin, v_period, to_char(v_filed_at, 'YYYY-MM-DD')
      USING ERRCODE = '42501';
  END IF;

  RETURN v_row;
END;
$$;

DROP TRIGGER IF EXISTS gstr2b_matches_not_filed ON gstr2b_matches;
CREATE TRIGGER gstr2b_matches_not_filed
  BEFORE INSERT OR UPDATE OR DELETE ON gstr2b_matches
  FOR EACH ROW EXECUTE FUNCTION enforce_gstr2b_match_not_filed();


-- ############################################################################
-- SECTION 7 — ⭐ THE SUMMARY MUST AGREE WITH ITS OWN MATCHES
-- ############################################################################
--
-- The two CHECK constraints in Section 1 prove the summary is INTERNALLY
-- consistent: books = matched + unmatched, on both sides. They say nothing
-- about whether those figures describe the matches actually stored, and that
-- is where the drift happens — the header is written by one statement and the
-- matches by another, and a partially-written re-run balances perfectly while
-- describing a reconciliation that does not exist.
--
-- ⚠️ A CONSTRAINT TRIGGER, DEFERRABLE INITIALLY DEFERRED, AND IT HAS TO BE. An
-- immediate trigger on `gstr2b_reconciliations` fires before any match exists
-- and would refuse every reconciliation ever created. COMMIT is the only point
-- at which the header and its matches are both present and both final.
--
-- ⚠️ AND IT ONLY FIRES WHERE MATCHES EXIST, exactly as the Phase 33 invoice
-- reconciliation only fires on `gst_computed` documents. A reconciliation row
-- created ahead of its run, or imported from a legacy system with totals only,
-- is not refused; one that CLAIMS to describe stored matches must describe
-- them.

CREATE OR REPLACE FUNCTION enforce_gstr2b_summary_agrees()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_rec           gstr2b_reconciliations%ROWTYPE;
  v_match_count   integer;
  v_matched_cnt   integer;
  v_matched_books bigint;
  v_matched_twob  bigint;
  v_books_only    bigint;
  v_twob_only     bigint;
BEGIN
  IF TG_TABLE_NAME = 'gstr2b_reconciliations' THEN
    v_rec := NEW;
  ELSE
    SELECT * INTO v_rec FROM gstr2b_reconciliations
     WHERE id = COALESCE(NEW.reconciliation_id, OLD.reconciliation_id);
    IF NOT FOUND THEN RETURN NULL; END IF;
  END IF;

  SELECT count(*) INTO v_match_count
    FROM gstr2b_matches m WHERE m.reconciliation_id = v_rec.id;

  -- Not run yet. Nothing to disagree with.
  IF v_match_count = 0 THEN RETURN NULL; END IF;

  SELECT
    count(*) FILTER (WHERE m.gstr2b_row_id IS NOT NULL
                       AND m.purchase_invoice_id IS NOT NULL),
    COALESCE(sum(i.cgst_minor + i.sgst_minor + i.igst_minor + i.cess_minor)
               FILTER (WHERE m.gstr2b_row_id IS NOT NULL
                         AND m.purchase_invoice_id IS NOT NULL), 0),
    COALESCE(sum(b.cgst_minor + b.sgst_minor + b.igst_minor + b.cess_minor)
               FILTER (WHERE m.gstr2b_row_id IS NOT NULL
                         AND m.purchase_invoice_id IS NOT NULL), 0),
    COALESCE(sum(i.cgst_minor + i.sgst_minor + i.igst_minor + i.cess_minor)
               FILTER (WHERE m.gstr2b_row_id IS NULL), 0),
    COALESCE(sum(b.cgst_minor + b.sgst_minor + b.igst_minor + b.cess_minor)
               FILTER (WHERE m.purchase_invoice_id IS NULL), 0)
    INTO v_matched_cnt, v_matched_books, v_matched_twob, v_books_only, v_twob_only
    FROM gstr2b_matches m
    LEFT JOIN purchase_invoices i ON i.id = m.purchase_invoice_id
    LEFT JOIN gstr2b_rows      b ON b.id = m.gstr2b_row_id
   WHERE m.reconciliation_id = v_rec.id;

  IF v_matched_cnt <> v_rec.matched_count THEN
    RAISE EXCEPTION
      'The GSTR-2B reconciliation for % % says % documents matched; % match rows '
      'carry both a supplier declaration and a purchase invoice. A count that '
      'disagrees with its own rows is a count nobody can check.',
      v_rec.gstin, v_rec.tax_period, v_rec.matched_count, v_matched_cnt
      USING ERRCODE = '23514';
  END IF;

  IF v_matched_books <> v_rec.matched_books_tax_minor
     OR v_matched_twob <> v_rec.matched_twob_tax_minor THEN
    RAISE EXCEPTION
      'The GSTR-2B reconciliation for % % does not agree with its own matches: '
      'the matched rows carry % paise of tax on the books side and % on the 2B '
      'side, and the summary says % and %.',
      v_rec.gstin, v_rec.tax_period, v_matched_books, v_matched_twob,
      v_rec.matched_books_tax_minor, v_rec.matched_twob_tax_minor
      USING ERRCODE = '23514';
  END IF;

  IF v_books_only <> v_rec.in_books_not_in_2b_tax_minor THEN
    RAISE EXCEPTION
      '⭐ The GSTR-2B reconciliation for % % says % paise of tax is in the books '
      'and not in 2B; the match rows carry %. That figure is the input tax '
      'credit Section 16(2)(aa) does NOT allow until the supplier files, and a '
      'summary that understates it reports suppliers as having filed when they '
      'have not.',
      v_rec.gstin, v_rec.tax_period, v_rec.in_books_not_in_2b_tax_minor, v_books_only
      USING ERRCODE = '23514';
  END IF;

  IF v_twob_only <> v_rec.in_2b_not_in_books_tax_minor THEN
    RAISE EXCEPTION
      'The GSTR-2B reconciliation for % % says % paise of tax is in 2B and not in '
      'the books; the match rows carry %.',
      v_rec.gstin, v_rec.tax_period, v_rec.in_2b_not_in_books_tax_minor, v_twob_only
      USING ERRCODE = '23514';
  END IF;

  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS gstr2b_reconciliations_summary_agrees ON gstr2b_reconciliations;
CREATE CONSTRAINT TRIGGER gstr2b_reconciliations_summary_agrees
  AFTER INSERT OR UPDATE ON gstr2b_reconciliations
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION enforce_gstr2b_summary_agrees();

DROP TRIGGER IF EXISTS gstr2b_matches_summary_agrees ON gstr2b_matches;
CREATE CONSTRAINT TRIGGER gstr2b_matches_summary_agrees
  AFTER INSERT OR UPDATE OR DELETE ON gstr2b_matches
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION enforce_gstr2b_summary_agrees();


-- ############################################################################
-- SECTION 8 — ⭐ A MATCH MAY NOT CROSS A STATEMENT OR A PERIOD
-- ############################################################################
--
-- The composite foreign keys in Section 4 stop a match pointing at ANOTHER
-- TENANT'S rows. This stops something narrower and entirely within one tenant:
--
--     A match under July's reconciliation for GSTIN 27… that points at a 2B
--     row belonging to AUGUST's statement, or to the statement of the
--     Karnataka registration.
--
-- ⚠️ WHY IT MATTERS. A developer registered in two states has two 2B
-- statements a month and two electronic credit ledgers that never mix — Section
-- 16(1) gives the credit to the registered person who received the supply. A
-- match that reaches across them reconciles Maharashtra's books against
-- Karnataka's statement, and the credit it appears to justify is in a ledger
-- with nothing to set it against.
--
-- ⚠️ AND ACROSS PERIODS IT IS SUBTLER AND WORSE: July's reconciliation matching
-- an August 2B row would report the supplier as having filed IN JULY, which is
-- the whole question Section 16(2)(aa) turns on.

CREATE OR REPLACE FUNCTION enforce_gstr2b_match_within_statement()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_rec_gstin   varchar(15);
  v_rec_period  varchar(7);
  v_row_gstin   varchar(15);
  v_row_period  varchar(7);
BEGIN
  IF NEW.gstr2b_row_id IS NULL THEN RETURN NEW; END IF;

  SELECT r.gstin, r.tax_period INTO v_rec_gstin, v_rec_period
    FROM gstr2b_reconciliations r WHERE r.id = NEW.reconciliation_id;
  IF NOT FOUND THEN RETURN NEW; END IF;

  SELECT d.gstin, d.return_period INTO v_row_gstin, v_row_period
    FROM gstr2b_rows w
    JOIN gstr2b_documents d ON d.id = w.document_id
   WHERE w.id = NEW.gstr2b_row_id;
  IF NOT FOUND THEN RETURN NEW; END IF;

  IF v_row_gstin <> v_rec_gstin THEN
    RAISE EXCEPTION
      'This match is under the reconciliation for GSTIN % but the supplier '
      'declaration comes from the GSTR-2B of GSTIN %. Input tax credit belongs '
      'to the electronic credit ledger of the registration that received the '
      'supply (Section 16(1)) — matching across two registrations justifies a '
      'credit in a ledger with nothing to set it against.',
      v_rec_gstin, v_row_gstin
      USING ERRCODE = '23514';
  END IF;

  IF v_row_period <> v_rec_period THEN
    RAISE EXCEPTION
      'This match is under the % reconciliation but the supplier declaration '
      'comes from the % statement. Whether the supplier filed IN THIS PERIOD is '
      'the entire question Section 16(2)(aa) turns on, and a match across '
      'periods answers it wrongly in the direction that claims the credit.',
      v_rec_period, v_row_period
      USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;

