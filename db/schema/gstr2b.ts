/**
 * ⭐⭐ THE SEVEN OUTCOMES, AND WHY THERE ARE SEVEN RATHER THAN TWO.
 *
 * "Matched / unmatched" is the design everybody reaches for and it is
 * useless in practice, because the four unmatched kinds need four
 * different people to do four different things:
 *
 *   exact              — GSTIN, invoice number, date, taxable value and
 *                        every tax head agree. ⭐ THE ONLY CATEGORY THAT
 *                        MAY EVER BE ACCEPTED WITHOUT A HUMAN.
 *
 *   probable           — GSTIN and invoice number agree; a value differs.
 *                        Usually line-level rounding: they footed the
 *                        invoice, we footed the lines. The delta is
 *                        recorded in paise and a person decides. ⚠️ A
 *                        large delta is ALSO this category, at low
 *                        confidence — it is still the same document, and
 *                        pretending otherwise would report the invoice
 *                        as both missing and unrecorded.
 *
 *   number_mismatch    — same supplier, same date, same value, and the
 *                        invoice number differs only in punctuation:
 *                        `INV-001` / `INV/001` / `INV 001` / `INV1`.
 *                        ⚠️ NORMALISED FOR COMPARISON ONLY. The
 *                        supplier's number is never overwritten with
 *                        ours — theirs is what the portal holds, and it
 *                        is what any future correspondence quotes.
 *
 *   in_2b_not_in_books — the supplier filed something we never recorded.
 *                        A bill lost in the post, or an invoice raised
 *                        against our GSTIN by somebody we do not deal
 *                        with. The second is fraud and looks exactly
 *                        like the first.
 *
 *   in_books_not_in_2b — ⭐ THE EXPENSIVE ONE. We have the bill, we paid
 *                        it, and the supplier has not filed. Section
 *                        16(2)(aa) means the credit is not available.
 *                        Every day it stays here is a day closer to the
 *                        Section 16(4) cliff, after which it is gone
 *                        permanently.
 *
 *   amended            — a `b2ba`/`cdnra` row superseding an earlier
 *                        declaration. The amended figures replace the
 *                        original; they do not add to it.
 *
 *   cancelled          — the supplier withdrew the document. We hold an
 *                        invoice for a supply the supplier now says did
 *                        not happen, and any credit taken on it must be
 *                        reversed.
 */
export const gstr2bMatchCategoryEnum = pgEnum("gstr2b_match_category", [
  "exact",
  "probable",
  "number_mismatch",
  "in_2b_not_in_books",
  "in_books_not_in_2b",
  "amended",
  "cancelled",
]);

/**
 * How much the engine believes its own answer.
 *
 * ⚠️ SEPARATE FROM THE CATEGORY BECAUSE THE CATEGORY IS *WHAT* AND THIS
 * IS *HOW SURE*. A `probable` match that differs by 2 paise and a
 * `probable` match that differs by ₹40,000 are the same category and
 * nowhere near the same claim, and a worklist that cannot sort by the
 * second is a worklist nobody finishes.
 */
export const gstr2bMatchConfidenceEnum = pgEnum("gstr2b_match_confidence", [
  "exact",
  "high",
  "medium",
  "low",
  "none",
]);

/**
 * What a human decided about a proposed match.
 *
 * ⚠️ `deferred` IS NOT `pending`, AND THE DIFFERENCE IS A PERSON. Pending
 * means nobody has looked. Deferred means somebody looked, could not
 * resolve it this month, and expects it to resolve next month when the
 * supplier files. An ageing report that cannot tell those apart reports
 * a growing backlog either as neglect or as a supplier problem, and they
 * need opposite responses.
 */
export const gstr2bMatchActionEnum = pgEnum("gstr2b_match_action", [
  "pending",
  "accepted",
  "rejected",
  "deferred",
]);

/**
 * Where a reconciliation is in its life.
 *
 * ⚠️ `filed` IS A ONE-WAY DOOR. It records that a GSTR-3B was submitted
 * on the strength of these figures. From that moment the reconciliation
 * is a working paper for a document the Government holds, and the
 * trigger in SQL 0024 §6 refuses every further change to it — including,
 * and especially, a re-import of the same period, which the portal
 * itself invites by REGENERATING 2B whenever a supplier files late.
 */
export const gstr2bReconciliationStatusEnum = pgEnum("gstr2b_reconciliation_status", [
  "draft",
  "in_progress",
  "reconciled",
  "filed",
]);

