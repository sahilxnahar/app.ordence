-- ############################################################################
-- SECTION 9 — ⭐ SUPPORT SESSIONS MAY NOT DELETE TAX EVIDENCE
-- ############################################################################
--
-- Phase 17 installed `refuse_delete_under_impersonation()`. These four tables
-- join the list, and the argument for `gstr2b_documents` is the strongest in
-- the product:
--
-- ⚠️ IT IS THE ONE TABLE WHOSE CONTENTS CANNOT BE RECONSTRUCTED FROM ANYTHING
-- THE CUSTOMER HOLDS. A deleted purchase invoice can be re-entered from the
-- paper in the file. A deleted 2B statement can only be re-downloaded from a
-- portal that keeps two years of history — and the statement that mattered is
-- the one generated on the day the return was filed, which the portal will
-- never serve again because it has since been regenerated.
--
-- Written with a `to_regclass` check so the file stays runnable against a
-- database where Phase 17 has not been applied.

DO $$
DECLARE
  guarded text;
BEGIN
  IF EXISTS (SELECT 1 FROM pg_proc WHERE proname = 'refuse_delete_under_impersonation') THEN
    FOREACH guarded IN ARRAY ARRAY[
      'gstr2b_documents', 'gstr2b_rows', 'gstr2b_reconciliations', 'gstr2b_matches'
    ]
    LOOP
      IF to_regclass('public.' || guarded) IS NOT NULL THEN
        EXECUTE format(
          'DROP TRIGGER IF EXISTS %I ON %I', 'no_delete_under_impersonation', guarded
        );
        EXECUTE format(
          'CREATE TRIGGER %I BEFORE DELETE ON %I FOR EACH ROW '
          'EXECUTE FUNCTION refuse_delete_under_impersonation()',
          'no_delete_under_impersonation', guarded
        );
      END IF;
    END LOOP;
  END IF;
END
$$;


-- ############################################################################
-- SECTION 9b — updated_at, AND THE CHANGE LOG
-- ############################################################################

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['gstr2b_documents','gstr2b_rows',
                           'gstr2b_reconciliations','gstr2b_matches']
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS %I ON %I', t || '_set_updated_at', t);
    EXECUTE format(
      'CREATE TRIGGER %I BEFORE UPDATE ON %I
         FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
      t || '_set_updated_at', t);
  END LOOP;

  -- ⚠️ ALL FOUR, INCLUDING `gstr2b_rows`, AND THE ARGUMENT FOR LEAVING IT OUT
  -- WAS CONSIDERED AND REJECTED.
  --
  -- The case against: a large developer's monthly statement runs to tens of
  -- thousands of rows, rebuilt whenever the statement is re-parsed, and the
  -- rows are DERIVED — the thing that has to be provable is the raw document
  -- they came from, and that is logged, immutable and hashed. Logging the rows
  -- makes the change log the largest table in the database.
  --
  -- The case for, which wins: the change log is not only evidence, it is how a
  -- table SYNCS. A tenant-scoped table with no trigger simply never
  -- replicates, and the omission is silent — nobody finds out until data is
  -- missing on one machine and present on another, with no error and nothing
  -- to point at. `tests/security/change-log.test.ts` DISCOVERS the gap rather
  -- than reading a list, for exactly that reason, and an exemption argued from
  -- storage cost is the shape every such gap has when it is introduced.
  IF EXISTS (SELECT 1 FROM pg_proc WHERE proname = 'record_change') THEN
    FOREACH t IN ARRAY ARRAY['gstr2b_documents','gstr2b_rows',
                             'gstr2b_reconciliations','gstr2b_matches']
    LOOP
      EXECUTE format('DROP TRIGGER IF EXISTS %I ON %I', t || '_change_log', t);
      EXECUTE format(
        'CREATE TRIGGER %I AFTER INSERT OR UPDATE OR DELETE ON %I
           FOR EACH ROW EXECUTE FUNCTION record_change()',
        t || '_change_log', t);
    END LOOP;
  END IF;
END
$$;


-- ############################################################################
-- SECTION 10 — GRANTS
-- ############################################################################
--
-- REVOKE before GRANT. An additive-only block is defeated by any prior
-- `GRANT ALL ON ALL TABLES`, which is the first thing most people run when a
-- query fails with "permission denied". Found the hard way in Phase 11.
--
-- ⚠️ NO DELETE ON `gstr2b_documents`, AND THAT IS THE POINT OF THE TABLE.
-- The statement is the evidence. It is the only artefact in the product that
-- the customer cannot reconstruct from their own paper, and the portal will
-- not serve the same generation of it twice.
--
-- ⚠️ NO DELETE ON `gstr2b_reconciliations` EITHER. A filed reconciliation is a
-- working paper for a return the Government holds; an unfiled one is the audit
-- trail of what was looked at before it was filed. A wrong reconciliation is
-- superseded by re-running it, not removed.
--
-- `gstr2b_rows` and `gstr2b_matches` DO get DELETE, and the asymmetry is the
-- design: both are DERIVED from the raw document by a deterministic engine, and
-- re-running the engine has to be able to replace them. What protects them once
-- they matter is the FREEZE (Section 6), not the grant — because a match under
-- a filed reconciliation must be immovable while a match under a draft one must
-- be replaceable, and a GRANT cannot tell those apart.

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ordence_app') THEN
    REVOKE ALL ON gstr2b_documents       FROM ordence_app;
    REVOKE ALL ON gstr2b_rows            FROM ordence_app;
    REVOKE ALL ON gstr2b_reconciliations FROM ordence_app;
    REVOKE ALL ON gstr2b_matches         FROM ordence_app;

    GRANT SELECT, INSERT, UPDATE         ON gstr2b_documents       TO ordence_app;
    GRANT SELECT, INSERT, UPDATE, DELETE ON gstr2b_rows            TO ordence_app;
    GRANT SELECT, INSERT, UPDATE         ON gstr2b_reconciliations TO ordence_app;
    GRANT SELECT, INSERT, UPDATE, DELETE ON gstr2b_matches         TO ordence_app;
  END IF;
END
$$;


