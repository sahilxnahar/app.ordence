export type RecordTypeKey = keyof typeof RECORD_TYPES;

export const RECORD_TYPE_KEYS = Object.keys(RECORD_TYPES) as RecordTypeKey[];

/**
 * ⚠️ `Object.hasOwn`, never `in`. `"constructor"` passes an `in` test on
 * any object literal, and a record type of "constructor" resolving to a
 * function is the start of a much worse afternoon.
 */
export function isRecordType(value: unknown): value is RecordTypeKey {
  return typeof value === "string" && Object.hasOwn(RECORD_TYPES, value);
}

export function recordTypeFor(value: unknown): RecordTypeDefinition | null {
  return isRecordType(value) ? RECORD_TYPES[value] : null;
}

