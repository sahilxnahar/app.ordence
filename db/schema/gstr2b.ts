/**
 * Ordence — ⭐ GSTR-2B RECONCILIATION
 * Version: v0.34.0-alpha
 *
 * ══════════════════════════════════════════════════════════════════════
 * WHAT GSTR-2B IS, AND WHY IT OUTRANKS OUR OWN BOOKS
 * ══════════════════════════════════════════════════════════════════════
 * GSTR-2B is a static monthly statement the GST portal generates for a
 * GSTIN. It lists every document that OUR SUPPLIERS filed against us in
 * their own GSTR-1 — invoice by invoice, with the tax they declared.
 *
 * Section 16(2)(aa), in force from 1 January 2022, makes it the ceiling:
 *
 *     "…the details of the invoice or debit note have been furnished by
 *      the supplier in the statement of outward supplies and such details
 *      have been communicated to the recipient of such invoice…"
 *
 * So the credit is not ours because we hold a tax invoice and paid the
 * tax. It is ours because the SUPPLIER filed. Rule 36(4) removed the old
 * 5% tolerance entirely in 2022; there is now no cushion at all.
 *
 * ⭐ THE CONSEQUENCE, STATED PLAINLY: a bill we have, have paid, and hold
 * a perfect tax invoice for, carries NO input tax credit if the supplier
 * did not file their GSTR-1. Nothing in our own records shows this. The
 * bill looks identical to one that is fine. The only way to know is to
 * compare our purchase register against a document generated by somebody
 * else, every month, invoice by invoice.
 *
 * That comparison is this phase.
 *
 * ══════════════════════════════════════════════════════════════════════
 * ⚠️ WHY THE MATCH ITSELF IS A STORED, EXPLAINED FACT AND NOT A QUERY
 * ══════════════════════════════════════════════════════════════════════
 * The obvious design is a view: join purchase invoices to 2B rows on
 * GSTIN and invoice number, count what falls out. It fails on the first
 * real month, for a reason that has nothing to do with SQL.
 *
 *   • The supplier types `INV-001`. We typed `INV/001` off the same
 *     paper. A join on equality reports both an unfiled supplier AND an
 *     unrecorded purchase, from ONE invoice, and the two errors are in
 *     opposite directions so the totals still look plausible.
 *   • The supplier declared ₹1,00,000.00 taxable; our line-level
 *     rounding produced ₹99,999.98. Same invoice, different number.
 *   • A finance manager has to defend every accepted match to an
 *     officer, months later, when the underlying rows have moved on.
 *
 * So a match is a ROW: which 2B line, which purchase invoice, WHICH
 * FIELDS AGREED, what differed and by how many paise, what confidence
 * the engine assigned, and who accepted it. Re-running the engine
 * produces the same answer from the same inputs — and where it does not,
 * `engine_version` says why.
 *
 * ══════════════════════════════════════════════════════════════════════
 * ⚠️ THE RAW DOCUMENT IS THE EVIDENCE. THE PARSED ROWS ARE AN OPINION.
 * ══════════════════════════════════════════════════════════════════════
 * `gstr2b_documents.raw_document` holds the file exactly as it was
 * downloaded, and it is immutable by trigger (SQL 0024 §5). The parsed
 * `gstr2b_rows` are derived and may be dropped and rebuilt.
 *
 * The asymmetry is deliberate and it is the most important line in this
 * file. A parse bug is discovered by definition AFTER the parse — often
 * a year later, at a notice. If the import overwrote the raw file with
 * its own interpretation, there is nothing left to re-read, and the only
 * remaining copy of what the Government actually said about us is on a
 * portal that keeps two years of history.
 *
 * ══════════════════════════════════════════════════════════════════════
 * ⚠️ AND A FILED PERIOD FREEZES
 * ══════════════════════════════════════════════════════════════════════
 * Once a GSTR-3B has been filed for a period, the reconciliation that
 * supported it is the working paper for a return the Government holds a
 * copy of. Re-importing 2B for that period — which people do, because
 * the portal REGENERATES 2B when a supplier files late — must not
 * silently rewrite it. The trigger in SQL 0024 §6 refuses.
 *
 * Money is `bigint` paise. Rates are integer basis points.
 */

