-- ⚠️  READ THIS BEFORE THE SQL
-- ============================================================================
-- Section 16(2)(aa) of the CGST Act, in force from 1 January 2022, makes the
-- SUPPLIER'S FILING a precondition of our input tax credit. Rule 36(4) removed
-- the last provisional cushion in the same year. So:
--
--     A bill we hold, have paid, and have a perfect tax invoice for carries NO
--     input tax credit if the supplier did not file their GSTR-1.
--
-- Nothing in our own records shows this. The bill looks identical to one that
-- is fine. The only way to know is to compare our purchase register against a
-- document generated by somebody else, every month, invoice by invoice.
--
-- Three failure modes are worth enforcing in the database, because all three
-- are silent and all three are profitable in the short run:
--
--   • Section 5 — THE RAW FILE IS DESTROYED. A parse bug is discovered by
--     definition after the parse, often a year later at a notice, and by then
--     the portal may no longer serve that month. An import that overwrote the
--     raw document with its own interpretation would leave nothing to re-read.
--
--   • Section 6 — A FILED PERIOD IS SILENTLY REWRITTEN. The portal REGENERATES
--     GSTR-2B whenever a supplier files late, so re-importing July in November
--     is ordinary work. If July's reconciliation moved, the working paper for
--     a GSTR-3B the Government holds a copy of would no longer describe what
--     was filed, and nothing anywhere would say it had changed.
--
--   • Sections 1, 2 and 7 — THE SUMMARY STOPS ADDING UP. If one invoice is
--     matched twice, or dropped, the totals still look like totals. Every row
--     on every screen is correct. The only symptom is that "in books, not in
--     2B" is SMALLER than it should be — which reads as good news, fewer
--     suppliers to chase, more credit available. The credit is then claimed on
--     an invoice the supplier never filed.
--
-- And one rule about people rather than data:
--
--   • Section 1 — NOTHING BELOW AN EXACT MATCH MAY BE ACCEPTED WITHOUT A NAMED
--     HUMAN. "Auto-accept everything above 90%" is the most requested feature
--     in every reconciliation product ever built, and it produces a year of
--     matches nobody looked at, discovered at the one assessment where the
--     answer to "who decided this" has to be a person.
--
-- Money is bigint paise. Rates are integer basis points.
-- ============================================================================


-- ############################################################################
-- SECTION 1 — ENUMS AND TABLES
-- ############################################################################
--
-- `drizzle-kit push` creates these from `db/schema/gstr2b.ts`. They are
-- restated here because a file that can only run second is a file that fails on
-- a fresh database.

DO $$
BEGIN
  -- The portal's own section names. ⚠️ NOT interchangeable: a `b2ba` row
  -- SUPERSEDES an earlier invoice rather than adding to it, and an `impg` row
  -- is a bill of entry with no supplier GSTIN at all.
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'gstr2b_section') THEN
    CREATE TYPE gstr2b_section AS ENUM
      ('b2b','b2ba','cdnr','cdnra','isd','isda','impg','impgsez');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'gstr2b_source_format') THEN
    CREATE TYPE gstr2b_source_format AS ENUM ('portal_json','portal_excel','csv');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'gstr2b_parse_status') THEN
    CREATE TYPE gstr2b_parse_status AS ENUM ('pending','parsed','failed');
  END IF;

  -- ⚠️ The PORTAL'S opinion, which is not the same question as Section 17(5).
  -- A row can be available here and still be BLOCKED by our own determination.
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'gstr2b_itc_availability') THEN
    CREATE TYPE gstr2b_itc_availability AS ENUM ('available','not_available');
  END IF;

  -- ⭐ THE SEVEN OUTCOMES. See db/schema/gstr2b.ts for why there are seven
  -- rather than "matched / unmatched": the four unmatched kinds need four
  -- different people to do four different things.
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'gstr2b_match_category') THEN
    CREATE TYPE gstr2b_match_category AS ENUM
      ('exact','probable','number_mismatch','in_2b_not_in_books',
       'in_books_not_in_2b','amended','cancelled');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'gstr2b_match_confidence') THEN
    CREATE TYPE gstr2b_match_confidence AS ENUM ('exact','high','medium','low','none');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'gstr2b_match_action') THEN
    CREATE TYPE gstr2b_match_action AS ENUM ('pending','accepted','rejected','deferred');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'gstr2b_reconciliation_status') THEN
    CREATE TYPE gstr2b_reconciliation_status AS ENUM
      ('draft','in_progress','reconciled','filed');
  END IF;
END
$$;


-- ⭐ THE EVIDENCE. One row per downloaded statement, stored whole.
CREATE TABLE IF NOT EXISTS gstr2b_documents (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id         uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  registration_id   uuid,
  gstin             varchar(15) NOT NULL,
  return_period     varchar(7)  NOT NULL,
  source_format     gstr2b_source_format NOT NULL,
  file_name         varchar(255),
  file_hash         varchar(64) NOT NULL,
  file_byte_size    bigint,
  generated_on      date,
  portal_version    varchar(16),
  raw_document      jsonb NOT NULL,
  parse_status      gstr2b_parse_status NOT NULL DEFAULT 'pending',
  parse_error       text,
  parse_issues      jsonb NOT NULL DEFAULT '[]'::jsonb,
  row_count         integer NOT NULL DEFAULT 0,
  parsed_at         timestamptz,
  imported_by       uuid,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT gstr2b_documents_period_shape
    CHECK (return_period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  -- ⚠️ A failed parse must say why, and a successful one must not carry a
  -- stale reason — that is how a fixed import gets re-investigated.
  CONSTRAINT gstr2b_documents_failure_explained
    CHECK ((parse_status = 'failed') = (parse_error IS NOT NULL)),
  -- ⭐ The evidence may not be blank.
  CONSTRAINT gstr2b_documents_raw_present
    CHECK (jsonb_typeof(raw_document) IS NOT NULL AND raw_document <> 'null'::jsonb),
  CONSTRAINT gstr2b_documents_hash_shape
    CHECK (file_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT gstr2b_documents_count_sane CHECK (row_count >= 0)
);


-- The parsed rows. ⚠️ DERIVED AND REBUILDABLE — the raw document is not.
CREATE TABLE IF NOT EXISTS gstr2b_rows (
  id                       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id                uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  document_id              uuid NOT NULL,
  section                  gstr2b_section NOT NULL,
  supplier_gstin           varchar(15),
  supplier_legal_name      varchar(255),
  supplier_trade_name      varchar(255),
  invoice_number           varchar(64) NOT NULL,
  normalised_number        varchar(64) NOT NULL,
  invoice_date             date NOT NULL,
  document_type            varchar(12),
  document_value_minor     bigint NOT NULL DEFAULT 0,
  taxable_value_minor      bigint NOT NULL DEFAULT 0,
  cgst_minor               bigint NOT NULL DEFAULT 0,
  sgst_minor               bigint NOT NULL DEFAULT 0,
  igst_minor               bigint NOT NULL DEFAULT 0,
  cess_minor               bigint NOT NULL DEFAULT 0,
  place_of_supply_code     varchar(2),
  is_reverse_charge        boolean NOT NULL DEFAULT false,
  itc_available            gstr2b_itc_availability NOT NULL DEFAULT 'available',
  itc_unavailable_reason   varchar(120),
  supplier_filing_period   varchar(7),
  supplier_filing_date     date,
  is_amendment             boolean NOT NULL DEFAULT false,
  original_invoice_number  varchar(64),
  original_invoice_date    date,
  is_cancelled             boolean NOT NULL DEFAULT false,
  rate_breakup             jsonb NOT NULL DEFAULT '[]'::jsonb,
  source_ref               varchar(160),
  created_at               timestamptz NOT NULL DEFAULT now(),
  updated_at               timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT gstr2b_rows_non_negative
    CHECK (document_value_minor >= 0 AND taxable_value_minor >= 0
           AND cgst_minor >= 0 AND sgst_minor >= 0
           AND igst_minor >= 0 AND cess_minor >= 0),
  -- ⚠️ A row carrying IGST *and* the CGST/SGST pair means the columns were
  -- mapped wrongly out of a spreadsheet. That is the single most common CSV
  -- import failure and it silently doubles the credit for a whole month.
  CONSTRAINT gstr2b_rows_heads_exclusive
    CHECK (NOT (igst_minor > 0 AND (cgst_minor > 0 OR sgst_minor > 0))),
  -- ⭐ An amendment SUPERSEDES the original; without the original's number the
  -- credit would be counted twice.
  CONSTRAINT gstr2b_rows_amendment_names_original
    CHECK (NOT is_amendment OR original_invoice_number IS NOT NULL),
  -- ⚠️ Only an import of goods legitimately has no supplier GSTIN — the
  -- counterparty is Customs. Anything else without one would sit in the
  -- worklist forever as an unmatched supplier who does not exist.
  CONSTRAINT gstr2b_rows_gstin_presence
    CHECK (supplier_gstin IS NOT NULL OR section = 'impg'),
  CONSTRAINT gstr2b_rows_filing_period_shape
    CHECK (supplier_filing_period IS NULL
           OR supplier_filing_period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$')
);


-- ⭐ THE PERIOD'S RECONCILIATION, ITS TOTALS, AND ITS FREEZE.
CREATE TABLE IF NOT EXISTS gstr2b_reconciliations (
  id                          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id                   uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  registration_id             uuid,
  gstin                       varchar(15) NOT NULL,
  tax_period                  varchar(7)  NOT NULL,
  document_id                 uuid,
  status                      gstr2b_reconciliation_status NOT NULL DEFAULT 'draft',

  books_invoice_count         integer NOT NULL DEFAULT 0,
  books_taxable_minor         bigint  NOT NULL DEFAULT 0,
  books_tax_minor             bigint  NOT NULL DEFAULT 0,
  books_itc_eligible_minor    bigint  NOT NULL DEFAULT 0,

  twob_row_count              integer NOT NULL DEFAULT 0,
  twob_taxable_minor          bigint  NOT NULL DEFAULT 0,
  twob_tax_minor              bigint  NOT NULL DEFAULT 0,
  twob_itc_available_minor    bigint  NOT NULL DEFAULT 0,

  matched_count               integer NOT NULL DEFAULT 0,
  matched_books_tax_minor     bigint  NOT NULL DEFAULT 0,
  matched_twob_tax_minor      bigint  NOT NULL DEFAULT 0,

  in_books_not_in_2b_count    integer NOT NULL DEFAULT 0,
  in_books_not_in_2b_tax_minor bigint NOT NULL DEFAULT 0,
  itc_at_risk_minor           bigint  NOT NULL DEFAULT 0,

  in_2b_not_in_books_count    integer NOT NULL DEFAULT 0,
  in_2b_not_in_books_tax_minor bigint NOT NULL DEFAULT 0,

  itc_claimed_minor           bigint  NOT NULL DEFAULT 0,

  engine_version              varchar(16) NOT NULL DEFAULT '1',
  last_run_at                 timestamptz,

  filed_at                    timestamptz,
  filed_by                    uuid,
  filed_reference             varchar(64),

  notes                       text,
  created_by                  uuid,
  created_at                  timestamptz NOT NULL DEFAULT now(),
  updated_at                  timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT gstr2b_reconciliations_period_shape
    CHECK (tax_period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT gstr2b_reconciliations_non_negative
    CHECK (books_invoice_count >= 0 AND books_taxable_minor >= 0
           AND books_tax_minor >= 0 AND books_itc_eligible_minor >= 0
           AND twob_row_count >= 0 AND twob_taxable_minor >= 0
           AND twob_tax_minor >= 0 AND twob_itc_available_minor >= 0
           AND matched_count >= 0 AND matched_books_tax_minor >= 0
           AND matched_twob_tax_minor >= 0
           AND in_books_not_in_2b_count >= 0 AND in_books_not_in_2b_tax_minor >= 0
           AND in_2b_not_in_books_count >= 0 AND in_2b_not_in_books_tax_minor >= 0
           AND itc_at_risk_minor >= 0 AND itc_claimed_minor >= 0),

  -- ⭐⭐ THE TWO IDENTITIES THE WHOLE SUMMARY RESTS ON.
  --
  --     books tax = matched (books side) + in books, not in 2B
  --     2B tax    = matched (2B side)    + in 2B, not in books
  --
  -- ⚠️ IF EITHER FAILS, AN INVOICE IS NOT IN EXACTLY ONE BUCKET — counted
  -- twice, or dropped. A dropped invoice makes "in books, not in 2B" SMALLER
  -- than it should be, which reads as good news: fewer suppliers to chase.
  -- The credit is then claimed under Section 16(2)(aa) with nothing behind it.
  CONSTRAINT gstr2b_reconciliations_books_reconcile
    CHECK (books_tax_minor = matched_books_tax_minor + in_books_not_in_2b_tax_minor),
  CONSTRAINT gstr2b_reconciliations_twob_reconcile
    CHECK (twob_tax_minor = matched_twob_tax_minor + in_2b_not_in_books_tax_minor),

  -- ⭐ A filed reconciliation names when it was filed, and vice versa.
  CONSTRAINT gstr2b_reconciliations_filed_consistent
    CHECK ((status = 'filed') = (filed_at IS NOT NULL))
);


-- ⭐⭐ THE MATCH. What matched, why, and who said so.
CREATE TABLE IF NOT EXISTS gstr2b_matches (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id             uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  reconciliation_id     uuid NOT NULL,
  gstr2b_row_id         uuid,
  purchase_invoice_id   uuid,
  vendor_id             uuid,
  supplier_gstin        varchar(15),

  match_category        gstr2b_match_category NOT NULL,
  confidence            gstr2b_match_confidence NOT NULL,
  match_score           integer NOT NULL DEFAULT 0,

  matched_on            jsonb NOT NULL DEFAULT '[]'::jsonb,
  differences           jsonb NOT NULL DEFAULT '[]'::jsonb,

  taxable_delta_minor   bigint NOT NULL DEFAULT 0,
  tax_delta_minor       bigint NOT NULL DEFAULT 0,
  itc_at_risk_minor     bigint NOT NULL DEFAULT 0,
  ambiguous_candidates  integer NOT NULL DEFAULT 0,

  explanation           text NOT NULL,
  engine_version        varchar(16) NOT NULL DEFAULT '1',

  action                gstr2b_match_action NOT NULL DEFAULT 'pending',
  action_reason         text,
  action_by             uuid,
  action_at             timestamptz,

  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT gstr2b_matches_has_a_side
    CHECK (gstr2b_row_id IS NOT NULL OR purchase_invoice_id IS NOT NULL),

  -- ⚠️ The category and the pointers must agree. An `exact` match with no
  -- purchase invoice is a contradiction, and it is the shape a
  -- partially-written re-run leaves behind.
  CONSTRAINT gstr2b_matches_category_matches_sides
    CHECK (CASE match_category
             WHEN 'in_2b_not_in_books'
               THEN gstr2b_row_id IS NOT NULL AND purchase_invoice_id IS NULL
             WHEN 'in_books_not_in_2b'
               THEN purchase_invoice_id IS NOT NULL AND gstr2b_row_id IS NULL
             ELSE gstr2b_row_id IS NOT NULL AND purchase_invoice_id IS NOT NULL
           END),

  -- ⭐⭐ NOTHING BELOW AN EXACT MATCH MAY BE ACCEPTED WITHOUT A NAMED HUMAN.
  --
  -- ⚠️ IN THE DATABASE BECAUSE THE ENGINE IS ONE WRITE PATH OF SEVERAL. A
  -- bulk-accept button, an import script and a future API route are the
  -- others, and "accept everything above 90%" is the most requested feature in
  -- every reconciliation product ever built. It is also the one that produces
  -- a year of matches nobody looked at, discovered at the one assessment where
  -- the answer to "who decided this" has to be a person.
  CONSTRAINT gstr2b_matches_no_silent_auto_accept
    CHECK (NOT (action = 'accepted'
                AND match_category <> 'exact'
                AND action_by IS NULL)),

  -- ⚠️ A rejection or a deferral with no reason explains nothing. Three months
  -- later "why is this still open" has no answer, and the exception is
  -- re-investigated from scratch every month until somebody accepts it to make
  -- it go away.
  CONSTRAINT gstr2b_matches_refusal_has_reason
    CHECK (action NOT IN ('rejected','deferred')
           OR (action_by IS NOT NULL AND action_reason IS NOT NULL)),

  CONSTRAINT gstr2b_matches_action_timed
    CHECK ((action = 'pending') = (action_at IS NULL)),
  CONSTRAINT gstr2b_matches_score_range
    CHECK (match_score >= 0 AND match_score <= 100),
  CONSTRAINT gstr2b_matches_non_negative
    CHECK (itc_at_risk_minor >= 0 AND ambiguous_candidates >= 0),

  -- ⚠️ An `exact` match with a delta is not an exact match. The LABEL is what
  -- a reviewer trusts and the DELTA is what an officer finds.
  CONSTRAINT gstr2b_matches_exact_has_no_delta
    CHECK (match_category <> 'exact'
           OR (taxable_delta_minor = 0 AND tax_delta_minor = 0
               AND confidence = 'exact'))
);


