/* THE CATALOGUE                                                       */
/* ------------------------------------------------------------------ */

export type RecordTypeDefinition = {
  /** The real table. Never taken from a definition. */
  table: string;
  label: string;
  /**
   * Columns a workflow may WRITE.
   *
   * ⚠️ NOTE WHAT IS ABSENT FROM EVERY LIST: `id`, `tenant_id`,
   * `created_at`, `deleted_at`, `deleted_by`, and every column another
   * phase's trigger depends on. `units.status` is missing for exactly
   * that reason — Phase 22 spent a whole file making unit status
   * coherent, and an automation that sets it directly walks around
   * `enforce_unit_bookable` and `bookings_sync_unit` in one line.
   * A workflow books a unit by creating a booking, like everybody else.
   */
  writableColumns: readonly string[];
  /** Columns a workflow may READ or filter on. */
  readableColumns: readonly string[];
  /** Columns that must be present on a create. */
  requiredOnCreate: readonly string[];
  permissions: {
    read: string;
    create: string | null;
    update: string | null;
    /** `null` means this record type cannot be deleted by an automation. */
    delete: string | null;
  };
  /**
   * True when "delete" means `deleted_at = now()`.
   *
   * ⚠️ Every deletable type here is soft-deleted, and that is not a
   * coincidence: the application role holds no DELETE grant on any of
   * them (Phase 22, Section 9). A hard DELETE from a workflow step would
   * fail with 42501 halfway through a run, leaving the earlier steps
   * committed and the author staring at "permission denied" for an
   * action the builder offered them.
   */
  softDelete: boolean;
};

