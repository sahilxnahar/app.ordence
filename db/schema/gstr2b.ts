/**
 * The sections of a GSTR-2B, named exactly as the portal's JSON names
 * them.
 *
 * ⚠️ THEY ARE NOT INTERCHANGEABLE AND THE ARITHMETIC DIFFERS BY SECTION.
 *
 *   b2b     — ordinary supplier invoices. The bulk.
 *   b2ba    — ⭐ AMENDMENTS to invoices declared in an EARLIER period.
 *             An amendment SUPERSEDES the original: the credit is the
 *             amended figure, not the sum of the two. Treating a `b2ba`
 *             row as another invoice double-counts the whole document.
 *   cdnr    — credit and debit notes from a registered supplier. A
 *             CREDIT note REDUCES our credit; a DEBIT note increases it.
 *             ⚠️ Both arrive as positive numbers with a type flag, so a
 *             parser that ignores `nttyp` gets the sign backwards on
 *             every return.
 *   cdnra   — amendments to those notes.
 *   isd     — Input Service Distributor documents: credit distributed
 *             from a head office registration to this one.
 *   isda    — amendments to those.
 *   impg    — ⭐ IMPORTS OF GOODS. A bill of entry, not an invoice. There
 *             is no supplier GSTIN at all — the counterparty is Customs
 *             — so every match rule keyed on GSTIN is inapplicable and
 *             the key is the bill-of-entry number and port code.
 *   impgsez — imports from an SEZ unit. Same shape, and the SEZ DOES
 *             have a GSTIN.
 */
export const gstr2bSectionEnum = pgEnum("gstr2b_section", [
  "b2b",
  "b2ba",
  "cdnr",
  "cdnra",
  "isd",
  "isda",
  "impg",
  "impgsez",
]);

/**
 * How the statement reached us.
 *
 * ⚠️ THE CSV/EXCEL PATH IS NOT A CONVENIENCE, IT IS THE COMMON CASE. The
 * portal's JSON download is the authoritative artefact, and almost no
 * accountant has one: they open the Excel, or their consultant emails a
 * sheet. Refusing everything but JSON means the feature is used by
 * nobody and the reconciliation is done in a spreadsheet instead — which
 * is the status quo this phase exists to replace.
 *
 * ⚠️ AND THE FORMAT IS RECORDED BECAUSE IT CHANGES WHAT WE CAN PROVE. A
 * portal JSON carries the checksum and the generation date; a
 * hand-edited sheet carries neither, and a match built on one is
 * evidence of a different quality. Storing the format is how a later
 * reader can tell the two apart.
 */
export const gstr2bSourceFormatEnum = pgEnum("gstr2b_source_format", [
  "portal_json",
  "portal_excel",
  "csv",
]);

/**
 * ⚠️ `failed` IS A STATE OF THE DOCUMENT, NOT AN ABSENCE OF ONE. A file
 * that would not parse is still stored, in full, with the reason. The
 * alternative — refusing the insert — throws away the only copy of the
 * thing that has to be looked at to fix the parser.
 */
export const gstr2bParseStatusEnum = pgEnum("gstr2b_parse_status", [
  "pending",
  "parsed",
  "failed",
]);

/**
 * Whether the portal says the credit on a 2B row is available to us.
 *
 * ⚠️ THIS IS THE PORTAL'S OPINION AND IT IS NOT THE SAME QUESTION AS
 * SECTION 17(5). The portal marks `itcavl = 'N'` for a handful of
 * mechanical reasons — the supplier filed after the Section 16(4)
 * deadline, the place of supply and the supplier's state are the same as
 * ours so the credit belongs to another state, the document is from a
 * period beyond the limit. It knows nothing about whether the cement
 * went into a building we are selling or one we are keeping.
 *
 * So a row can be `available` here and still be BLOCKED by Phase 33's
 * determination, and the reconciliation must show both. Collapsing them
 * into one flag is how a blocked credit gets claimed because "2B says
 * it's available".
 */
export const gstr2bItcAvailabilityEnum = pgEnum("gstr2b_itc_availability", [
  "available",
  "not_available",
]);

