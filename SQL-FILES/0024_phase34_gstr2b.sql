-- ⚠️ `SET CONSTRAINTS … IMMEDIATE` IS WHAT MAKES THE SECOND HALF MEAN
-- ANYTHING. The summary guard is DEFERRABLE INITIALLY DEFERRED, so it fires at
-- COMMIT — and this whole DO block ends in a deliberate rollback, so COMMIT
-- never happens and the offending row would appear to succeed. Forcing the
-- constraint IMMEDIATE inside the sub-block fires the pending events there.
--
-- ⚠️ AND THE INSERT AND THE `SET CONSTRAINTS` MUST BE IN THE **SAME** plpgsql
-- BEGIN…EXCEPTION BLOCK. When a subtransaction aborts, the after-trigger events
-- queued inside it are discarded; events queued OUTSIDE it are not, and would
-- fire again at the block's own rollback and surface as an unrelated failure.
DO $$
DECLARE
  v_tenant    uuid := gen_random_uuid();
  v_rec       uuid := gen_random_uuid();
  v_doc       uuid := gen_random_uuid();
  v_row       uuid := gen_random_uuid();
  v_vendor    uuid := gen_random_uuid();
  v_inv1      uuid := gen_random_uuid();
  v_inv2      uuid := gen_random_uuid();
  v_identity_refused boolean := false;
  v_twice_refused    boolean := false;
  v_agrees_refused   boolean := false;
BEGIN
  INSERT INTO tenants (id, clerk_org_id, slug, name, status)
    VALUES (v_tenant, 'org_2bsum_' || v_tenant, 'sum-' || left(v_tenant::text, 8),
            'GSTR-2B summary verification', 'active');
  INSERT INTO vendors (id, tenant_id, code, legal_name)
    VALUES (v_vendor, v_tenant, 'V-SUM', 'Verification Supplier');
  INSERT INTO gstr2b_documents
    (id, tenant_id, gstin, return_period, source_format, file_hash, raw_document)
    VALUES (v_doc, v_tenant, '27AAACR5055K1ZQ', '2024-07', 'portal_json',
            repeat('f', 64), '{"data":{"gstin":"x"}}'::jsonb);
  INSERT INTO gstr2b_rows
    (id, tenant_id, document_id, section, supplier_gstin, invoice_number,
     normalised_number, invoice_date, taxable_value_minor, cgst_minor, sgst_minor)
    VALUES (v_row, v_tenant, v_doc, 'b2b', '29AAACR5055K1ZP', 'INV-001', 'INV1',
            DATE '2024-07-05', 10000000, 900000, 900000);
  INSERT INTO purchase_invoices
    (id, tenant_id, vendor_id, supplier_gstin, invoice_number, invoice_date,
     subtotal_minor, taxable_value_minor, cgst_minor, sgst_minor, total_minor,
     itc_eligible_tax_minor)
    VALUES
    (v_inv1, v_tenant, v_vendor, '29AAACR5055K1ZP', 'INV-001', DATE '2024-07-05',
     10000000, 10000000, 900000, 900000, 11800000, 1800000),
    (v_inv2, v_tenant, v_vendor, '29AAACR5055K1ZP', 'INV-009', DATE '2024-07-09',
     10000000, 10000000, 900000, 900000, 11800000, 1800000);

  -- ⭐ A summary whose books total does not equal matched + unmatched.
  -- MUST be refused by the CHECK, immediately.
  BEGIN
    INSERT INTO gstr2b_reconciliations
      (tenant_id, gstin, tax_period, status,
       books_tax_minor, matched_books_tax_minor, in_books_not_in_2b_tax_minor)
      VALUES (v_tenant, '27AAACR5055K1ZQ', '2024-09', 'in_progress',
              3600000, 1800000, 900000);
  EXCEPTION WHEN OTHERS THEN
    v_identity_refused := true;
  END;

  INSERT INTO gstr2b_reconciliations
    (id, tenant_id, gstin, tax_period, document_id, status,
     books_tax_minor, matched_books_tax_minor, in_books_not_in_2b_tax_minor,
     twob_tax_minor, matched_twob_tax_minor, matched_count)
    VALUES (v_rec, v_tenant, '27AAACR5055K1ZQ', '2024-07', v_doc, 'in_progress',
            3600000, 1800000, 1800000, 1800000, 1800000, 1);

  INSERT INTO gstr2b_matches
    (tenant_id, reconciliation_id, gstr2b_row_id, purchase_invoice_id,
     supplier_gstin, match_category, confidence, match_score, explanation)
    VALUES (v_tenant, v_rec, v_row, v_inv1, '29AAACR5055K1ZP', 'exact', 'exact',
            100, 'Every field agrees.');
  INSERT INTO gstr2b_matches
    (tenant_id, reconciliation_id, purchase_invoice_id, supplier_gstin,
     match_category, confidence, match_score, explanation, itc_at_risk_minor)
    VALUES (v_tenant, v_rec, v_inv2, '29AAACR5055K1ZP', 'in_books_not_in_2b',
            'none', 0, 'The supplier has not filed this invoice.', 1800000);

  -- ⭐ The SAME 2B row matched to a SECOND purchase invoice. Both rows look
  -- ordinary. MUST be refused by the one-to-one index.
  BEGIN
    INSERT INTO gstr2b_matches
      (tenant_id, reconciliation_id, gstr2b_row_id, purchase_invoice_id,
       supplier_gstin, match_category, confidence, match_score, explanation)
      VALUES (v_tenant, v_rec, v_row, v_inv2, '29AAACR5055K1ZP', 'probable',
              'high', 90, 'Same supplier and number.');
  EXCEPTION WHEN OTHERS THEN
    v_twice_refused := true;
  END;

  -- ⭐ And a summary that claims figures its own matches do not support.
  BEGIN
    UPDATE gstr2b_reconciliations
       SET books_tax_minor = 5400000,
           matched_books_tax_minor = 1800000,
           in_books_not_in_2b_tax_minor = 3600000
     WHERE id = v_rec;
    SET CONSTRAINTS gstr2b_reconciliations_summary_agrees,
                    gstr2b_matches_summary_agrees IMMEDIATE;
    SET CONSTRAINTS gstr2b_reconciliations_summary_agrees,
                    gstr2b_matches_summary_agrees DEFERRED;
  EXCEPTION WHEN OTHERS THEN
    v_agrees_refused := true;
  END;

  IF v_identity_refused AND v_twice_refused AND v_agrees_refused THEN
    RAISE NOTICE 'PASS: ⭐ a summary that does not add up is refused, one 2B row '
                 'cannot be matched to two purchase invoices, and the stored totals '
                 'must describe the matches actually held.';
  ELSIF NOT v_identity_refused THEN
    RAISE WARNING '*** FAIL — ⭐⭐ A SUMMARY THAT DOES NOT ADD UP WAS ACCEPTED. An '
                  'invoice is then in no bucket, "in books, not in 2B" is smaller '
                  'than it should be, and that reads as GOOD NEWS — fewer suppliers '
                  'to chase. The credit is claimed under Section 16(2)(aa) with '
                  'nothing behind it. ***';
  ELSIF NOT v_twice_refused THEN
    RAISE WARNING '*** FAIL — one GSTR-2B row was matched to TWO purchase invoices. '
                  'Both rows look ordinary; the matched total exceeds the books '
                  'total and one supplier drops off the chase list. ***';
  ELSE
    RAISE WARNING '*** FAIL — a reconciliation''s stored totals were allowed to '
                  'disagree with its own match rows, so the summary describes a '
                  'reconciliation that does not exist. ***';
  END IF;

  RAISE EXCEPTION 'verification rollback';
EXCEPTION WHEN OTHERS THEN
  IF SQLERRM <> 'verification rollback' THEN
    RAISE WARNING '*** FAIL — verification could not run: % ***', SQLERRM;
  END IF;
END
$$;


-- Check 9 — the app role cannot DELETE the evidence.
SELECT
  t.table_name, t.privilege_type,
  '*** FAIL — DELETE granted: the only artefact the customer cannot reconstruct '
  'from their own paper can be erased ***' AS verdict
FROM information_schema.role_table_grants t
WHERE t.grantee = 'ordence_app'
  AND t.privilege_type = 'DELETE'
  AND t.table_name IN ('gstr2b_documents','gstr2b_reconciliations');
-- (No rows returned = PASS.)


-- Check 10 — nothing points across a tenant boundary TODAY.
SELECT 'gstr2b rows → documents' AS relationship, count(*) AS violations,
       CASE WHEN count(*) = 0 THEN 'PASS' ELSE '*** FAIL ***' END AS verdict
  FROM gstr2b_rows r JOIN gstr2b_documents d ON d.id = r.document_id
 WHERE r.tenant_id <> d.tenant_id
UNION ALL
SELECT 'matches → reconciliations', count(*),
       CASE WHEN count(*) = 0 THEN 'PASS' ELSE '*** FAIL ***' END
  FROM gstr2b_matches m JOIN gstr2b_reconciliations c ON c.id = m.reconciliation_id
 WHERE m.tenant_id <> c.tenant_id
UNION ALL
SELECT 'matches → purchase invoices', count(*),
       CASE WHEN count(*) = 0 THEN 'PASS' ELSE '*** FAIL ***' END
  FROM gstr2b_matches m JOIN purchase_invoices i ON i.id = m.purchase_invoice_id
 WHERE m.tenant_id <> i.tenant_id
UNION ALL
SELECT 'matches → gstr2b rows', count(*),
       CASE WHEN count(*) = 0 THEN 'PASS' ELSE '*** FAIL ***' END
  FROM gstr2b_matches m JOIN gstr2b_rows r ON r.id = m.gstr2b_row_id
 WHERE m.tenant_id <> r.tenant_id;


-- Check 11 — ⭐ every reconciliation in the database adds up TODAY.
-- Belt and braces: if the CHECKs were added after data existed, a wrong row
-- could predate them. This is the single query an auditor would run first.
SELECT
  CASE WHEN count(*) = 0
       THEN 'PASS: every GSTR-2B reconciliation balances on both sides'
       ELSE '*** FAIL — ' || count(*) || ' reconciliation(s) do not balance. An '
            'invoice is in no bucket or in two, and the credit at risk is '
            'misstated in the direction that looks like good news. ***'
  END AS check_summaries_balance
FROM gstr2b_reconciliations
WHERE books_tax_minor <> matched_books_tax_minor + in_books_not_in_2b_tax_minor
   OR twob_tax_minor  <> matched_twob_tax_minor + in_2b_not_in_books_tax_minor;


-- Check 12 — ⭐ no match anywhere has been accepted below EXACT with nobody
-- named against it.
SELECT
  CASE WHEN count(*) = 0
       THEN 'PASS: every accepted match below EXACT names the person who accepted it'
       ELSE '*** FAIL — ' || count(*) || ' match(es) below EXACT are ACCEPTED with '
            'no person named. At an assessment the answer to "who decided this" is '
            '"nobody did". ***'
  END AS check_no_silent_accepts
FROM gstr2b_matches
WHERE action = 'accepted' AND match_category <> 'exact' AND action_by IS NULL;


-- Check 13 — ⭐ a support session cannot DELETE GSTR-2B evidence.
SELECT
  expected.tbl,
  CASE WHEN t.tgname IS NOT NULL THEN 'PASS'
       ELSE '*** FAIL — an impersonating operator can delete from this table. For '
            'gstr2b_documents that destroys the only artefact the customer cannot '
            'reconstruct, and the portal will not serve the same generation twice ***'
  END AS verdict
FROM (VALUES
  ('gstr2b_documents'), ('gstr2b_rows'),
  ('gstr2b_reconciliations'), ('gstr2b_matches')
) AS expected(tbl)
LEFT JOIN pg_trigger t
       ON t.tgname = 'no_delete_under_impersonation'
      AND t.tgrelid = expected.tbl::regclass
      AND NOT t.tgisinternal
ORDER BY expected.tbl;


-- Check 14 — the change log covers this phase, ALL FOUR TABLES.
-- ⚠️ Including `gstr2b_rows`. The change log is not only evidence, it is how a
-- tenant-scoped table SYNCS — a table without the trigger simply never
-- replicates, silently, until data is missing on one machine and present on
-- another.
SELECT
  expected.tbl,
  CASE WHEN t.tgname IS NOT NULL THEN 'PASS'
       ELSE '*** FAIL — changes here are not recorded and could never sync ***'
  END AS verdict
FROM (VALUES
  ('gstr2b_documents'), ('gstr2b_rows'),
  ('gstr2b_reconciliations'), ('gstr2b_matches')
) AS expected(tbl)
LEFT JOIN pg_trigger t
       ON t.tgname = expected.tbl || '_change_log'
      AND t.tgrelid = expected.tbl::regclass
      AND NOT t.tgisinternal
ORDER BY expected.tbl;


-- Check 15 — the one-to-one match indexes exist.
SELECT
  expected.indexname,
  CASE WHEN i.indexname IS NOT NULL THEN 'PASS'
       ELSE '*** FAIL: MISSING — a re-run can match one document to two, the '
            'matched total exceeds the books total, and a supplier drops off the '
            'chase list ***'
  END AS verdict
FROM (VALUES
  ('gstr2b_matches_one_per_2b_row'),
  ('gstr2b_matches_one_per_invoice'),
  ('gstr2b_documents_identity_unique'),
  ('gstr2b_reconciliations_period_unique')
) AS expected(indexname)
LEFT JOIN pg_indexes i ON i.indexname = expected.indexname
ORDER BY expected.indexname;
