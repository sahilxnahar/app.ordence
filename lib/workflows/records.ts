/**
 * Ordence — What a Workflow May Touch
 * Version: v0.23.0-alpha
 *
 * Pure. A frozen catalogue, no database access.
 *
 * ══════════════════════════════════════════════════════════════════════
 * ⭐ THIS FILE IS THE SECURITY BOUNDARY OF THE RECORD ACTIONS
 * ══════════════════════════════════════════════════════════════════════
 * `create_record`, `update_record`, `delete_record` and `find_records`
 * take a table name and a column list from a definition a TENANT WROTE.
 * Passed through to SQL, that is not an automation feature — it is an
 * arbitrary-statement primitive with a JSON front end:
 *
 *     recordType: "users"        → grant yourself a role
 *     values: { tenant_id: … }   → move a record into another workspace
 *     values: { deleted_at: … }  → empty a table one row at a time
 *     recordType: "audit_logs"   → write history that never happened
 *
 * None of those needs a database exploit. They need the executor to
 * believe the definition, which is why the executor never does.
 *
 * The rule this file exists to enforce is:
 *
 *   ⚠️ EVERY TABLE NAME AND EVERY COLUMN NAME THAT REACHES SQL COMES FROM
 *   THIS FROZEN OBJECT. Nothing from a workflow definition is ever
 *   interpolated into a statement — the definition only ever SELECTS from
 *   this catalogue, and an entry that is not here does not exist.
 *
 * Values are still parameterised, always. That protects against
 * injection. It does nothing about a workflow updating a column it was
 * never meant to reach, which is what an allow-list is for.
 */

